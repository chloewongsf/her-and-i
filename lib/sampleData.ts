function pick<T>(arr: T[], n: number): T[] {
  const copy = [...arr]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy.slice(0, n)
}

export function generateSessionPrompts() {
  return [
    pick(openers, 1)[0],
    ...pick(middlePool, 6),
    pick(closers, 1)[0],
  ]
}

